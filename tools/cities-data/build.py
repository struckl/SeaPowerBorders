"""Builds src/SeaPowerBorders/mod/places/world.csv from Natural Earth's populated places.

The game's own campaign lists (cities, ports, airports) are read by the mod at runtime from the player's install;
this file fills the rest of the world: every place of at least MIN_POPULATION people, and every capital. Names are
today's – the mod renames them by mission date (mod/places/eras.csv).

Input: ne_10m_populated_places_simple.geojson from Natural Earth (public domain), release v5.1.2:
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_populated_places_simple.geojson

    python -I tools/cities-data/build.py tools/cities-data/input/ne_10m_populated_places_simple.geojson \
        src/SeaPowerBorders/mod/places/world.csv
"""

import json
import sys

MIN_POPULATION = 350_000

# Natural Earth errors: Amaravati is a capital still being built, not a city of 5.8 million.
EXCLUDE = {("Amaravati", "IND")}


def main(source, target):
    with open(source, encoding="utf-8") as f:
        features = json.load(f)["features"]
    rows = []
    for feature in features:
        p = feature["properties"]
        capital = p["featurecla"] == "Admin-0 capital"
        if p["pop_max"] < MIN_POPULATION and not capital:
            continue
        name = " ".join(p["name"].split())
        if (name, p["adm0_a3"]) in EXCLUDE:
            continue
        rows.append((name, round(p["latitude"], 4), round(p["longitude"], 4), int(p["pop_max"]),
                     1 if capital else 0, p["adm0_a3"]))
    rows.sort(key=lambda r: -r[3])
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Natural Earth populated places (public domain), v5.1.2: places of at least "
                f"{MIN_POPULATION:,} people and every capital, today's names.\n")
        f.write("# Generated by tools/cities-data/build.py - do not edit by hand.\n")
        f.write("name;lat;lon;population;capital;country\n")
        for r in rows:
            f.write(";".join(str(v) for v in r) + "\n")
    print(f"{target}: {len(rows)} places")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
